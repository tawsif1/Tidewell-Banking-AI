-- Tidewell Bank schema. Running this file DELETES all bank data and recreates empty tables.

-- Start clean. CASCADE also removes anything that depends on these tables.
DROP TABLE IF EXISTS escalations, fee_reversals, disputes, cards, transactions, accounts, customers CASCADE;

CREATE TABLE customers (
    id            INTEGER PRIMARY KEY,
    full_name     TEXT    NOT NULL,
    date_of_birth DATE    NOT NULL,
    card_last4    TEXT    NOT NULL CHECK (card_last4 ~ '^[0-9]{4}$')   -- exactly 4 digits (a regex, like slugify)
);

CREATE TABLE accounts (
    id          INTEGER PRIMARY KEY,
    customer_id INTEGER NOT NULL REFERENCES customers(id),            -- must be a real customer
    type        TEXT    NOT NULL CHECK (type IN ('checking', 'savings', 'tfsa')),
    balance     NUMERIC(12, 2) NOT NULL
);

CREATE TABLE cards (
    id            INTEGER PRIMARY KEY,
    customer_id   INTEGER NOT NULL REFERENCES customers(id),
    last4         TEXT    NOT NULL CHECK (last4 ~ '^[0-9]{4}$'),
    type          TEXT    NOT NULL CHECK (type IN ('debit', 'credit')),
    status        TEXT    NOT NULL CHECK (status IN ('active', 'frozen', 'cancelled')),
    freeze_reason TEXT
);

CREATE TABLE transactions (
    -- The seed inserts the existing IDs (5001-5016); new rows get the next number automatically.
    id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id  INTEGER NOT NULL REFERENCES accounts(id),
    date        DATE    NOT NULL,
    description TEXT    NOT NULL,
    amount      NUMERIC(12, 2) NOT NULL,                              -- negative = money out
    type        TEXT    NOT NULL CHECK (type IN ('purchase', 'deposit', 'transfer', 'fee', 'fee_reversal')),
    status      TEXT    NOT NULL CHECK (status IN ('pending', 'posted')),
    fee_type    TEXT    CHECK (fee_type IN ('overdraft', 'nsf', 'wire', 'monthly'))   -- optional: only fees have one
);

-- IDs like DSP-1001: a sequence hands out numbers, and the default adds the prefix.
CREATE SEQUENCE dispute_number_seq START 1001;
CREATE TABLE disputes (
    id             TEXT    PRIMARY KEY DEFAULT ('DSP-' || nextval('dispute_number_seq')),
    transaction_id INTEGER NOT NULL UNIQUE REFERENCES transactions(id),   -- UNIQUE: one dispute per transaction
    customer_id    INTEGER NOT NULL REFERENCES customers(id),
    reason         TEXT    NOT NULL CHECK (reason IN ('unauthorized', 'not_received', 'duplicate_charge', 'incorrect_amount', 'other')),
    details        TEXT    NOT NULL,
    status         TEXT    NOT NULL DEFAULT 'open',
    filed_on       DATE    NOT NULL DEFAULT CURRENT_DATE
);
-- Tie the sequence to the table, so DROP TABLE removes it too.
ALTER SEQUENCE dispute_number_seq OWNED BY disputes.id;

CREATE SEQUENCE fee_reversal_number_seq START 2001;
CREATE TABLE fee_reversals (
    id             TEXT    PRIMARY KEY DEFAULT ('FR-' || nextval('fee_reversal_number_seq')),
    transaction_id INTEGER NOT NULL UNIQUE REFERENCES transactions(id),   -- UNIQUE: a fee can only be reversed once
    customer_id    INTEGER NOT NULL REFERENCES customers(id),
    amount         NUMERIC(12, 2) NOT NULL CHECK (amount > 0),
    reason         TEXT    NOT NULL,
    reversed_on    DATE    NOT NULL DEFAULT CURRENT_DATE
);
ALTER SEQUENCE fee_reversal_number_seq OWNED BY fee_reversals.id;

CREATE SEQUENCE escalation_number_seq START 3001;
CREATE TABLE escalations (
    id                    TEXT    PRIMARY KEY DEFAULT ('ESC-' || nextval('escalation_number_seq')),
    session_id            TEXT    NOT NULL,                       -- becomes a foreign key in plan step 5
    customer_id           INTEGER REFERENCES customers(id),       -- optional: unverified customers can escalate
    verified              BOOLEAN NOT NULL,
    actions_taken         TEXT[]  NOT NULL DEFAULT '{}',          -- a list of text; '{}' is an empty list
    category              TEXT    NOT NULL CHECK (category IN ('fraud', 'disputes', 'fees', 'cards', 'account_access', 'complaint', 'other')),
    priority              TEXT    NOT NULL CHECK (priority IN ('urgent', 'high', 'normal')),
    summary               TEXT    NOT NULL,
    still_needed          TEXT    NOT NULL,
    customer_sentiment    TEXT    NOT NULL,
    requested_by_customer BOOLEAN NOT NULL,
    queue                 TEXT    NOT NULL,
    status                TEXT    NOT NULL DEFAULT 'open',
    created_at            TIMESTAMPTZ NOT NULL DEFAULT now()
);
ALTER SEQUENCE escalation_number_seq OWNED BY escalations.id;